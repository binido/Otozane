"""Regenerates the bundled Lucide icon font subset and `crates/otozane-ui/src/icons.rs`.

Usage: python3 scripts/icons.py   (needs curl and fonttools' pyftsubset)
Add icon names to NAMES, then rerun.
"""
import json, os, subprocess, tempfile

VERSION = "1.62.0"
NAMES = [
    "mic", "mic-off", "power", "sliders-horizontal", "audio-lines", "puzzle", "folder-open",
    "settings", "plus", "trash-2", "grip-vertical", "circle-alert", "check", "x",
    "chevron-down", "chevron-right", "chevron-up", "save", "pencil", "refresh-cw", "activity",
    "sun", "moon", "monitor", "search", "copy", "gauge", "volume-2", "layers", "arrow-up",
    "arrow-down", "circle-check", "info", "bookmark", "list", "audio-waveform", "shield-check",
    "folder-plus", "plug", "loader-circle", "unplug", "radio", "sparkles", "arrow-right", "ellipsis-vertical", "brick-wall", "download", "upload",
]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "crates", "otozane-ui")
BASE = f"https://unpkg.com/lucide-static@{VERSION}"

with tempfile.TemporaryDirectory() as tmp:
    font, info = os.path.join(tmp, "lucide.ttf"), os.path.join(tmp, "info.json")
    subprocess.run(["curl", "-sfL", f"{BASE}/font/lucide.ttf", "-o", font], check=True)
    subprocess.run(["curl", "-sfL", f"{BASE}/font/info.json", "-o", info], check=True)
    data = json.load(open(info))
    codes = [data[n]["encodedCode"].lstrip("\\") for n in NAMES]
    subprocess.run(["pyftsubset", font, "--unicodes=" + ",".join("U+" + c for c in codes),
                    "--output-file=" + os.path.join(UI, "assets", "fonts", "lucide-subset.ttf")],
                   check=True)

lines = [f"//! Lucide icon codepoints (lucide-static {VERSION}, ISC license).",
         "//! Generated by `scripts/icons.py`; do not edit by hand.", ""]
for n, c in zip(NAMES, codes):
    lines.append(f'pub const {n.upper().replace("-", "_")}: &str = "\\u{{{c}}}";')
open(os.path.join(UI, "src", "icons.rs"), "w").write("\n".join(lines) + "\n")
print(f"{len(NAMES)} icons written")
